-- Everything in this app is shown in Philippine local time (the frontend
-- displays timestamps exactly as the database returns them), so all
-- timestamps below are stored as "timestamp without time zone" in Manila time.

DROP TABLE IF EXISTS wallet_transactions CASCADE;
DROP TABLE IF EXISTS sales CASCADE;
DROP TABLE IF EXISTS rentals CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS computers CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(100) NOT NULL,
  username    varchar(50)  NOT NULL UNIQUE,
  password    varchar(255) NOT NULL,
  role        varchar(20)  NOT NULL DEFAULT 'Staff'
              CHECK (role IN ('Administrator','Staff')),
  created_at  timestamp    NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------------------
-- computers
-- ---------------------------------------------------------------------
CREATE TABLE computers (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  computer_number varchar(20)   NOT NULL UNIQUE,
  computer_name   varchar(100),
  specifications  varchar(255),
  hourly_rate     numeric(10,2) NOT NULL,
  status          varchar(20)   NOT NULL DEFAULT 'Available'
                  CHECK (status IN ('Available','Occupied','Maintenance')),
  created_at      timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------------------
-- customers
-- ---------------------------------------------------------------------
CREATE TABLE customers (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name  varchar(100)  NOT NULL,
  contact_number varchar(20),
  email          varchar(100),
  wallet_balance numeric(10,2) NOT NULL DEFAULT 0.00,
  created_at     timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------
CREATE TABLE products (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_name   varchar(100)  NOT NULL,
  category       varchar(50),            -- e.g. Snack, Drink, Accessory
  price          numeric(10,2) NOT NULL,
  stock_quantity integer       NOT NULL DEFAULT 0,
  created_at     timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------------------
-- rentals
-- ---------------------------------------------------------------------
CREATE TABLE rentals (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_code      varchar(20)   NOT NULL UNIQUE,
  computer_id      integer       NOT NULL REFERENCES computers(id),
  customer_id      integer       REFERENCES customers(id),
  user_id          integer       NOT NULL REFERENCES users(id),
  time_in          timestamp     NOT NULL,
  time_out         timestamp,
  duration_minutes integer,
  rate_per_hour    numeric(10,2) NOT NULL,
  total_amount     numeric(10,2),
  status           varchar(20)   NOT NULL DEFAULT 'Ongoing'
                   CHECK (status IN ('Ongoing','Completed','Cancelled')),
  created_at       timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_rentals_computer ON rentals(computer_id);
CREATE INDEX idx_rentals_customer ON rentals(customer_id);
CREATE INDEX idx_rentals_user     ON rentals(user_id);

-- ---------------------------------------------------------------------
-- sales
-- ---------------------------------------------------------------------
CREATE TABLE sales (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     integer       NOT NULL REFERENCES products(id),
  quantity       integer       NOT NULL,
  unit_price     numeric(10,2) NOT NULL,   -- copied from product at time of sale
  subtotal       numeric(10,2) NOT NULL,
  customer_id    integer       REFERENCES customers(id),  -- NULL = walk-in
  user_id        integer       NOT NULL REFERENCES users(id), -- staff who processed it
  payment_method varchar(20)   NOT NULL DEFAULT 'Cash'
                 CHECK (payment_method IN ('Cash','Wallet')),
  created_at     timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_sales_product  ON sales(product_id);
CREATE INDEX idx_sales_customer ON sales(customer_id);
CREATE INDEX idx_sales_user     ON sales(user_id);

-- ---------------------------------------------------------------------
-- wallet_transactions
-- ---------------------------------------------------------------------
CREATE TABLE wallet_transactions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   integer       NOT NULL REFERENCES customers(id),
  type          varchar(20)   NOT NULL CHECK (type IN ('Load','Payment')),
  amount        numeric(10,2) NOT NULL,
  reference     varchar(100),
  balance_after numeric(10,2) NOT NULL,
  user_id       integer       NOT NULL REFERENCES users(id),
  created_at    timestamp     NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_wallet_customer ON wallet_transactions(customer_id);
CREATE INDEX idx_wallet_user     ON wallet_transactions(user_id);

